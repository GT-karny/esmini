def max_xy_between(a_pts, b_pts):
    """Largest XY distance from any point of polyline A to polyline B.

    Point-to-segment, not point-to-point: the two boundaries are refined
    independently and need not carry the same number of points."""
    worst = 0.0
    for p in a_pts:
        best = None
        for k in range(1, len(b_pts)):
            ax, ay = b_pts[k - 1]
            bx, by = b_pts[k]
            dx, dy = bx - ax, by - ay
            den = dx * dx + dy * dy
            u = 0.0 if den <= 0.0 else ((p[0] - ax) * dx + (p[1] - ay) * dy) / den
            u = max(0.0, min(1.0, u))
            d = math.hypot(p[0] - (ax + u * dx), p[1] - (ay + u * dy))
            if best is None or d < best:
                best = d
        if best is not None and best > worst:
            worst = best
    return worst


