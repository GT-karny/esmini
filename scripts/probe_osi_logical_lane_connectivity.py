def _run_worker(dll, rm_dll, fixtures, flag_on):
    """One subprocess per polarity, so the GT_OSI_LOGICAL_LANE latch is fresh."""
    out_fd, out_path = tempfile.mkstemp(suffix=".json")
    os.close(out_fd)
    src = _WORKER % {
        "repo": _REPO_ROOT,
        "out": out_path,
        "osi_file": os.path.join(tempfile.gettempdir(), "gt_ll_conn_probe.osi"),
        "fixtures": fixtures,
        "dll": dll,
        "rm_dll": rm_dll,
        "spec_xy": SPEC_ADJACENT_XY_M,
    }
    py_fd, py_path = tempfile.mkstemp(suffix=".py")
    with os.fdopen(py_fd, "w") as fh:
        fh.write(src)

    # The two polarities are "unset" and "0", NOT "1" and "unset": the variable has
    # been an OPT-OUT since S3, so leaving it unset is what exercises the default and
    # setting it to 0 is what exercises the escape hatch. Written the other way round
    # both runs would come out ON and every OFF assertion would pass vacuously.
    env = dict(os.environ)
    if flag_on:
        env.pop(ENV_FLAG, None)
    else:
        env[ENV_FLAG] = "0"

    proc = subprocess.run([sys.executable, py_path], env=env, capture_output=True, text=True,
                          cwd=_REPO_ROOT, timeout=3600)
    try:
        with open(out_path) as fh:
            result = json.load(fh)
    except Exception:  # noqa: BLE001
        result = {"fixtures": [], "error": "worker produced no JSON\n%s\n%s"
                  % (proc.stdout[-4000:], proc.stderr[-4000:])}
    result["worker_rc"] = proc.returncode
    for path in (out_path, py_path):
        try:
            os.unlink(path)
        except OSError:
            pass
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dll", default=DEFAULT_DLL)
    ap.add_argument("--rm-dll", default=DEFAULT_RM_DLL)
    args = ap.parse_args()

    os.makedirs(OUT_DIR, exist_ok=True)
    for path in (args.dll, args.rm_dll):
        if not os.path.exists(path):
            print("FAIL: no library at %s -- build Release first" % path)
            return 1

    failures = []
    report = {"dll": args.dll, "rm_dll": args.rm_dll}

    def check(name, ok, detail=""):
        print("  [%s] %s%s" % ("PASS" if ok else "FAIL", name, (" -- " + detail) if detail else ""))
        if not ok:
            failures.append("%s: %s" % (name, detail))

    fixtures = [[label, xodr] for (label, xodr) in FIXTURES]

    print("== GT_OSI_LOGICAL_LANE unset (default ON) ==")
    on = _run_worker(args.dll, args.rm_dll, fixtures, True)
    report["on"] = on
    if on.get("error"):
        check("worker_on", False, on["error"][-2000:])
        _write(report)
        return 1

    totals = {"cross_false": 0, "cross_true": 0, "junction_false": 0, "junction_true": 0,
              "adj_shared": 0, "adj_split": 0, "connecting_lanes": 0, "connecting_both": 0,
              "adj_control_xy": 0.0, "adj_control_pairs": 0}
    for r in on["fixtures"]:
        label = r["label"]
        print("  -- %s" % label)
        if r.get("error") or r["init_rc"] != 0:
            check("%s.init" % label, False, "%s (init rc=%s)" % (r.get("error"), r["init_rc"]))
            continue
        want_connections = r.get("meeting_opportunities_in_file", 0) > 0
        check("%s.connectivity_matches_the_file" % label,
              ((r["pred"] + r["succ"]) > 0) == want_connections,
              "%d predecessor / %d successor / %d left / %d right over %d logical lanes; the xodr "
              "offers %d lane-end meeting opportunit(y|ies), so connections are %s"
              % (r["pred"], r["succ"], r["left"], r["right"], r["logical_lanes"],
                 r.get("meeting_opportunities_in_file", -1),
                 "expected" if want_connections else "expected to be ABSENT"))
        check("%s.reference_closure" % label, r["dangling"] == 0,
              "%d/%d references resolve in logical_lane[]%s"
              % (r["pred"] + r["succ"] + r["left"] + r["right"] - r["dangling"],
                 r["pred"] + r["succ"] + r["left"] + r["right"],
                 ("; first dangling: %s" % r["dangling_examples"][0]) if r["dangling_examples"] else ""))
        check("%s.relation_ordering" % label, not r["order_bad"] and not r["range_bad"],
              "%d out-of-order, %d with end_s <= start_s" % (len(r["order_bad"]), len(r["range_bad"])))
        check("%s.contact_point_derivations_agree" % label, not r["contradictory_at_begin"],
              "%d lane(s) named twice with opposite at_begin (%d named as both predecessor and "
              "successor, which is legal)%s"
              % (len(r["contradictory_at_begin"]), r["both_pred_and_succ"],
                 ("; first: %s" % r["contradictory_at_begin"][0]) if r["contradictory_at_begin"] else ""))
        check("%s.adjacency_symmetric" % label, not r["adj_asymmetric"],
              "%d one-sided adjacency relation(s)%s"
              % (len(r["adj_asymmetric"]),
                 ("; first: %s" % r["adj_asymmetric"][0]) if r["adj_asymmetric"] else ""))
        check("%s.connections_reachable_from_both_ends" % label, not r["conn_asymmetric"],
              "%d connection entries, %d not mirrored%s"
              % (r["conn_meetings"], len(r["conn_asymmetric"]),
                 ("; first: %s" % r["conn_asymmetric"][0]) if r["conn_asymmetric"] else ""))
        check("%s.adjacent_boundaries_within_5cm" % label,
              not r["adj_bad"],
              "%d neighbour pairs: %d share a boundary id (0 by construction), %d split by height "
              "-- max XY %.4f m (spec %.2f), %d without boundaries%s"
              % (r["adj_pairs"], r["adj_shared_id"], r["adj_split"], r["adj_max_xy"],
                 SPEC_ADJACENT_XY_M, r["adj_no_boundary"],
                 ("; first bad: %s" % r["adj_bad"][0]) if r["adj_bad"] else ""))
        if r["connecting_lanes"]:
            check("%s.connecting_road_lanes_linked" % label,
                  r["connecting_with_pred"] == r["connecting_lanes"]
                  and r["connecting_with_succ"] == r["connecting_lanes"],
                  "%d connecting-road lanes (%d connecting roads in the file): %d with a predecessor, "
                  "%d with a successor%s"
                  % (r["connecting_lanes"], r.get("connecting_roads_in_file", -1),
                     r["connecting_with_pred"], r["connecting_with_succ"],
                     ("; missing: %s" % r["connecting_missing"][:3]) if r["connecting_missing"] else ""))
        print("       at_begin_of_other_lane [false, true]: same-road %s / cross-road %s / junction-touching %s"
              % (r["same_road_at_begin"], r["cross_road_at_begin"], r["junction_edge_at_begin"]))
        totals["cross_false"] += r["cross_road_at_begin"][0]
        totals["cross_true"] += r["cross_road_at_begin"][1]
        totals["junction_false"] += r["junction_edge_at_begin"][0]
        totals["junction_true"] += r["junction_edge_at_begin"][1]
        totals["adj_control_xy"] = max(totals.get("adj_control_xy", 0.0), r["adj_control_xy"])
        totals["adj_control_pairs"] += r["adj_control_pairs"]
        totals["adj_shared"] += r["adj_shared_id"]
        totals["adj_split"] += r["adj_split"]
        totals["connecting_lanes"] += r["connecting_lanes"]
        totals["connecting_both"] += min(r["connecting_with_pred"], r["connecting_with_succ"])

    report["totals"] = totals
    # The discriminating one. Inside a road the flag is structural; only a connection
    # that crosses a road boundary reads an OpenDRIVE @contactPoint, so a build that
    # never looked at one shows up here as a single polarity.
    check("at_begin_both_polarities_across_roads",
          totals["cross_true"] > 0 and totals["cross_false"] > 0,
          "cross-road connections: %d with at_begin=true, %d with at_begin=false"
          % (totals["cross_true"], totals["cross_false"]))
    check("at_begin_both_polarities_at_junctions",
          totals["junction_true"] > 0 and totals["junction_false"] > 0,
          "connections touching a connecting road: %d true, %d false"
          % (totals["junction_true"], totals["junction_false"]))
    # Both branches of the adjacency/boundary rule have to occur, or the 5cm check
    # only ever ran on pairs where it is 0 by construction.
    # Every adjacent pair measures 0 m, which is the right answer and also what a
    # dead instrument returns. This is the same function on a pair it must reject.
    check("adjacency_measurement_can_report_a_violation",
          totals["adj_control_xy"] > SPEC_ADJACENT_XY_M,
          "the same polyline comparison, run on %d deliberately WRONG pairs (this lane's right "
          "boundary vs the left neighbour's left boundary), reports up to %.3f m -- well past the "
          "%.2f m the check would fail at" % (totals["adj_control_pairs"], totals["adj_control_xy"],
                                              SPEC_ADJACENT_XY_M))
    check("adjacency_split_population_present", totals["adj_split"] > 0,
          "%d neighbour pairs share a boundary id, %d are split by height and therefore "
          "actually measured against the 5cm rule" % (totals["adj_shared"], totals["adj_split"]))

    print("== GT_OSI_LOGICAL_LANE=0 ==")
    off = _run_worker(args.dll, args.rm_dll, fixtures, False)
    report["off"] = off
    if off.get("error"):
        check("worker_off", False, off["error"][-2000:])
    else:
        for r in off["fixtures"]:
            check("%s.no_connectivity_when_off" % r["label"],
                  r["logical_lanes"] == 0 and (r["pred"] + r["succ"] + r["left"] + r["right"]) == 0,
                  "logical_lane[] = %d, connections = %d"
                  % (r["logical_lanes"], r["pred"] + r["succ"] + r["left"] + r["right"]))
        # The OFF run has to be non-vacuous in the other direction too: if it had
        # silently run with the feature ON, the counts above would have been non-zero.
        check("off_run_is_the_other_polarity",
              any(x["logical_lanes"] == 0 for x in off["fixtures"])
              and any(x["logical_lanes"] > 0 for x in on["fixtures"]),
              "ON produced logical lanes and OFF produced none")

    _write(report)
    print()
    if failures:
        print("FAIL (%d):" % len(failures))
        for f in failures:
            print("  - " + f)
        return 1
    print("PASS -- report: %s" % os.path.join(OUT_DIR, "connectivity_probe.json"))
    return 0


def _write(report):
    with open(os.path.join(OUT_DIR, "connectivity_probe.json"), "w") as fh:
        json.dump(report, fh, indent=1)


if __name__ == "__main__":
    sys.exit(main())
